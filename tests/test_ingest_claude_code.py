import argparse
from pathlib import Path

from jibun_kit import cli
from jibun_kit.config import JibunConfig
from jibun_kit.ingest import claude_code

FIX = Path(__file__).parent / "fixtures" / "claude_code"


def _args(**kw):
    base = dict(projects_root=FIX, session=None, all=True, since=None, until=None,
                dry_run=False, verbose=False)
    base.update(kw)
    return argparse.Namespace(**base)


def test_run_extracts_operator_only(tmp_workspace):
    rc = claude_code.run(JibunConfig(), _args(), tmp_workspace)
    assert rc == 0
    out = tmp_workspace.data_root / "claude-code" / "2026-05" / "sample-session.md"
    assert out.is_file()
    text = out.read_text(encoding="utf-8")
    assert "hello this is me" in text          # str user message
    assert "second real message" in text       # list-with-text user message
    # excluded:
    assert "sidechain text" not in text         # isSidechain
    assert "assistant reply" not in text        # type != user
    assert "<system-reminder>" not in text      # meta tag
    assert "toolout" not in text                # tool_result part dropped
    idx = (tmp_workspace.sources_root / "claude-code-index.md").read_text(encoding="utf-8")
    assert "session=sample-session" in idx
    assert "2 messages" in idx


def test_dry_run_writes_nothing(tmp_workspace):
    rc = claude_code.run(JibunConfig(), _args(dry_run=True), tmp_workspace)
    assert rc == 0
    assert not (tmp_workspace.data_root / "claude-code" / "2026-05" / "sample-session.md").exists()
    assert not (tmp_workspace.sources_root / "claude-code-index.md").exists()


def test_missing_projects_root_errors(tmp_workspace):
    # no CLI root, no config root -> unresolved
    rc = claude_code.run(JibunConfig(), _args(projects_root=None), tmp_workspace)
    assert rc == 2


def test_cli_dispatch_end_to_end(tmp_path):
    rc = cli.main(["ingest", "claude-code", "--path", str(tmp_path),
                   "--projects-root", str(FIX), "--all"])
    assert rc == 0
    assert (tmp_path / "data" / "claude-code" / "2026-05" / "sample-session.md").is_file()


def _write_jsonl(path, entries):
    import json
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(json.dumps(e, ensure_ascii=False) for e in entries) + "\n",
                    encoding="utf-8")


def _user(text, **extra):
    return {"type": "user", "timestamp": "2026-05-11T00:00:00Z",
            "message": {"role": "user", "content": text}, **extra}


def test_finds_sessions_in_project_subdirs(tmp_workspace, tmp_path):
    # ~/.claude/projects/ の実際の形: <project-slug>/<session-id>.jsonl
    root = tmp_path / "projects"
    _write_jsonl(root / "-example-proj-a" / "sess-a.jsonl", [_user("架空の発言A")])
    _write_jsonl(root / "-example-proj-b" / "sess-b.jsonl", [_user("架空の発言B")])
    assert claude_code.run(JibunConfig(), _args(projects_root=root), tmp_workspace) == 0
    names = sorted(p.name for p in (tmp_workspace.data_root / "claude-code").rglob("*.md"))
    assert names == ["sess-a.md", "sess-b.md"]

    # --session も配下から探す
    ws2 = tmp_path / "ws2"
    from jibun_kit.workspace import Workspace
    w = Workspace(ws2)
    rc = claude_code.run(JibunConfig(), _args(projects_root=root, all=False, session="sess-b"), w)
    assert rc == 0
    assert [p.name for p in (w.data_root / "claude-code").rglob("*.md")] == ["sess-b.md"]


def test_skips_meta_compact_summary_and_interrupt(tmp_workspace, tmp_path):
    root = tmp_path / "projects"
    _write_jsonl(root / "-p" / "s.jsonl", [
        _user("Caveat: The messages below were generated by the user ...", isMeta=True),
        _user("This session is being continued from a previous conversation ...",
              isCompactSummary=True),
        _user("[Request interrupted by user for tool use]"),
        _user([{"type": "text", "text": "[Request interrupted by user]"}]),
        _user("本人が打った架空の発言"),
    ])
    assert claude_code.run(JibunConfig(), _args(projects_root=root), tmp_workspace) == 0
    text = next((tmp_workspace.data_root / "claude-code").rglob("s.md")).read_text(
        encoding="utf-8")
    assert "本人が打った架空の発言" in text
    assert "Caveat" not in text
    assert "continued from a previous" not in text
    assert "Request interrupted" not in text
    assert "- messages: 1" in text
